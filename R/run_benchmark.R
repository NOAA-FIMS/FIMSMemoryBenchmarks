# Compare two FIMS refs using C++ profilers and bench::mark.
#
# This file does three things, in order: install each ref, profile each ref, and
# report. Profilers are run by scripts/memory.sh and scripts/performance.sh, one
# measurement per call; everything else happens here.
#
# Timing is deliberately absent. Wall-clock numbers for a stage belong in R,
# where bench::mark() can run both without a profiler distorting them.
#
# IMPORTANT: run this in an R session that has never loaded FIMS. Installing a
# different build over a mapped DLL is unreliable.

path_safe <- function(value) gsub("[^A-Za-z0-9._-]", "_", value)

# ---------------------------------------------------------------------------
# Does each profiler work here?
# ---------------------------------------------------------------------------
# Finding a binary on PATH is not the same as it working. When running in
# Virtual Machines such as WSL2 and Codespaces, the VMs will execute a
# separate tool binary, which will result in the program not being able to
# locate the specific C++ profiler even when its is installed locally.
# Additionally, certain tools like perf need a metric (like CPU cycles,
# memory checks, or a cache miss) that it can actually count. Under VMs,
# valgrind and perf can be installed but still fail, and siltently.
# `test_valgrind_works()` runs valgrind against /bin/true and
# `test_perf_works()` runs perf against a brief busy loop, so a broken
# environment is caught fast. Every failure they report names the README
# section that says how to fix it.

# In a Codespace the repository's devcontainer is meant to make both profilers
# work, so a failure there is a problem with this repository rather than the
# user's machine. Elsewhere, such as WSL2, the README says how to fix it.
fix_profiler_message <- if (identical(Sys.getenv("CODESPACES"), "true")) {
  paste("This Codespace was built from the repository's devcontainer, so ",
        "valgrind and perf should work without error, so please report it to the ",
        "developers at https://github.com/NOAA-FIMS/FIMSMemoryBenchmarks/issues ",
        "and include this message.")
} else {
  "See \"Fixing Valgrind and perf installation\" in README.md."
}

#' Can Valgrind actually run Massif here?
#'
#' @return TRUE, or a string explaining what failed.
test_valgrind_works <- function() {
  if (!nzchar(Sys.which("valgrind"))) {
    return(paste("valgrind is not on PATH.", fix_profiler_message))
  }
  out <- tempfile("massif-check-")
  on.exit(unlink(paste0(out, "*")), add = TRUE)
  status <- suppressWarnings(
    system2("valgrind",
            c("--tool=massif", 
              paste0("--massif-out-file=", shQuote(paste0(out, "_%p"))),
              "/bin/true"),
            stdout = FALSE, stderr = FALSE))
  if (!identical(as.integer(status), 0L)) {
    return(paste0("`valgrind --tool=massif /bin/true` exited with status ", status,
                  ". \"unknown program massif-<arch>-linux\" means the tool ",
                  "binaries are missing or VALGRIND_LIB points at the wrong ",
                  "place. ", fix_profiler_message))
  }
  if (!length(Sys.glob(paste0(out, "*")))) {
    return(paste("Massif ran but wrote no output.", fix_profiler_message))
  }
  TRUE
}

#' Which perf metric can the hardware manager record?
#'
#' Perf defaults to measuring a metric generated by the physical CPU hardware, but 
#' virtual environments (like WSL2 or Codespaces) usually hide or block assess to 
#' that hardware. Under this situaltion, the cpu-clock software event usually still works,
#' and perf will happily record nothing at all rather than fail loudly, so this
#' checks that a recording actually lands.
#'
#' @return "" for the default event, "cpu-clock" if the fallback is needed, or a
#'   string explaining why neither works.
test_perf_works <- function() {
  if (!nzchar(Sys.which("perf"))) {
    return(paste("perf is not on PATH.", fix_profiler_message))
  }
  attempt <- function(event) {
    out <- tempfile("perf-check-")
    on.exit(unlink(out), add = TRUE)
    args <- c("record", "-q", "-o", shQuote(out))
    if (nzchar(event)) args <- c(args, "-e", event)
    # Not /bin/true: it exits before perf takes a single sample, so the check
    # failed on machines where perf works. A fraction of a second of work is
    # enough to land samples.
    busy <- c("sh", "-c", shQuote("i=0; while [ $i -lt 300000 ]; do i=$((i+1)); done"))
    status <- suppressWarnings(system2("perf", c(args, "--", busy),
                                       stdout = FALSE, stderr = FALSE))
    if (!identical(as.integer(status), 0L) || !file.exists(out)) return(FALSE)
    # perf exits 0 having recorded nothing when the event never fires.
    report <- suppressWarnings(system2("perf", c("report", "--stdio", "-i", shQuote(out)),
                                       stdout = TRUE, stderr = FALSE))
    any(grepl("%", report, fixed = TRUE))
  }
  if (attempt("")) return("")
  if (attempt("cpu-clock")) return("cpu-clock")
  paste0("`perf record` recorded no samples with either the default event or ",
         "cpu-clock. On WSL2 there is no hardware Performance Monitoring Unit, ",
         "and perf must match the running kernel. ", fix_profiler_message)
}

#' Validate and de-duplicate the refs a run will compare
#'
#' Every ref is compared against the first. Duplicates are dropped rather than
#' measured twice, and refs that differ only in characters that are not
#' filename-safe are rejected: they would write to the same paths and silently
#' overwrite each other.
#'
#' Separate from run_fims_benchmark() so it can be tested without installing
#' anything.
#'
#' @param ref_first Baseline branch, tag, or commit.
#' @param ref_compare One or more refs to compare against it.
#' @return The refs to measure, in order, first one first.
resolve_refs <- function(ref_first, ref_compare = character()) {
  if (!is.character(ref_first) || !is.character(ref_compare)) {
    stop("Refs must be character vectors.", call. = FALSE)
  }
  refs <- c(ref_first, ref_compare)
  if (!length(refs) || anyNA(refs) || !all(nzchar(refs))) {
    stop("Every ref must be a non-empty branch, tag, or commit name.", call. = FALSE)
  }
  if (any(grepl("\\s", refs))) {
    stop("Ref names cannot contain whitespace: ",
         paste(refs[grepl("\\s", refs)], collapse = ", "), call. = FALSE)
  }

  if (anyDuplicated(refs)) {
    warning("Dropping duplicate refs: ",
            paste(unique(refs[duplicated(refs)]), collapse = ", "), call. = FALSE)
    refs <- unique(refs)
  }

  safe_names <- vapply(refs, path_safe, character(1))
  if (anyDuplicated(safe_names)) {
    collisions <- refs[safe_names %in% safe_names[duplicated(safe_names)]]
    stop("These refs collide once made filename-safe: ",
         paste(collisions, collapse = ", "), call. = FALSE)
  }
  if (length(refs) == 1L) {
    warning("Only one distinct ref; measuring it once with nothing to compare.",
            call. = FALSE)
  }
  refs
}


# The commit a ref points at, so a cached build can be checked against it. A
# bare SHA is already immutable; a branch or tag has to be asked of the remote.
# NA means "could not tell", which forces a reinstall rather than risking a
# stale build.
resolve_ref_sha <- function(ref, repo = "https://github.com/NOAA-FIMS/FIMS") {
  if (grepl("^[0-9a-f]{7,40}$", ref)) return(ref)
  out <- suppressWarnings(
    system2("git", c("ls-remote", shQuote(repo), shQuote(ref)), stdout = TRUE, stderr = FALSE))
  if (!length(out) || !nzchar(out[[1]])) return(NA_character_)
  sub("\\s.*$", "", out[[1]])
}

# system2(stdout = file) truncates, so each subprocess would erase the previous
# one's output. Capture and append instead: the log is the only record of why a
# profiler or an install failed.
run_logged <- function(command, args, env = character(), log) {
  output <- suppressWarnings(system2(command, args, env = env,
                                     stdout = TRUE, stderr = TRUE))
  status <- attr(output, "status")
  cat(paste0("\n$ ", command, " ", paste(args, collapse = " "), "\n"),
      paste(output, collapse = "\n"), "\n", file = log, append = TRUE)
  list(status = if (is.null(status)) 0L else as.integer(status), output = output)
}


#' Tidy rows from one reference run
#'
#' The reference run saves what the model computed, whole, to an RDS. This turns
#' it into the rows results.tsv holds: peak memory and page faults, the fit where
#' there is one, and one row per parameter value, estimate and standard error.
#' On macOS the memory numbers come from the /usr/bin/time -l file written next
#' to the RDS instead.
#'
#' @param ref Git ref the run measured.
#' @param path The reference run's RDS.
#' @param version FIMS version of the build, for the rows.
#' @return A data frame of tidy rows; run_fims_benchmark() fills the columns
#'   only it knows, such as stage and size.
reference_rows <- function(ref, path, version = "") {
  values <- readRDS(path)

  # macOS writes these to the /usr/bin/time -l file rather than the RDS.
  time_metrics <- function(time_path) {
    if (!file.exists(time_path)) return(list())
    text <- readLines(time_path, warn = FALSE)
    grab <- function(label) {
      hit <- Filter(length, regmatches(text, regexec(
        paste0("^\\s*([0-9]+)\\s+", label, "\\s*$"), text)))
      if (length(hit)) as.numeric(hit[[1]][[2]]) else NULL
    }
    list(maximum_rss = grab("maximum resident set size"),
         peak_footprint = grab("peak memory footprint"),
         page_reclaims = grab("page reclaims"),
         page_faults = grab("page faults"),
         swaps = grab("swaps"))
  }
  from_time <- time_metrics(sub("[.]rds$", "_time.txt", path))

  # Standard errors are the Std. Error column of TMB's summary of the fixed
  # effects; sd_fixed is the name older runs saved them under.
  standard_errors <- if (!is.null(values$sdr_fixed)) {
    unname(values$sdr_fixed[, "Std. Error"])
  } else {
    values$sd_fixed
  }

  recorded <- list(
    maximum_rss = if (is.null(from_time$maximum_rss)) values$maximum_rss
                  else from_time$maximum_rss,
    stage_rss_added = values$stage_rss_added,
    peak_footprint = from_time$peak_footprint,
    page_reclaims = if (is.null(from_time$page_reclaims)) values$page_reclaims
                    else from_time$page_reclaims,
    page_faults = if (is.null(from_time$page_faults)) values$page_faults
                  else from_time$page_faults,
    swaps = from_time$swaps,
    final_objective = values$final_objective,
    initial_objective = values$initial_objective,
    final_gradient_max = if (is.null(values$final_gradient)) NULL else max(abs(values$final_gradient)),
    sd_fixed_max = if (is.null(standard_errors)) NULL else max(standard_errors),
    iterations = values$iterations,
    function_evaluations = values$function_evaluations,
    gradient_evaluations = values$gradient_evaluations,
    convergence = values$convergence,
    n_fixed = values$n_fixed, n_random = values$n_random)
  recorded <- recorded[!vapply(recorded, is.null, logical(1))]

  # One row per value. Parameter values carry their names, since the report
  # shows them; estimates and standard errors are numbered only, because the
  # report reads them back as estimate:<n> and standard_error:<n>.
  numbered <- function(prefix, x) {
    if (is.null(x) || !length(x)) return(NULL)
    x <- unlist(x)
    stats::setNames(as.list(unname(x)), paste0(prefix, seq_along(x)))
  }
  # initial_parameters is a list from initialize_fims() and a named vector from
  # parList(); unlist() turns either into one named vector.
  named <- function(prefix, x) {
    if (is.null(x) || !length(x)) return(NULL)
    x <- unlist(x)
    labels <- if (is.null(names(x))) rep("", length(x)) else names(x)
    stats::setNames(as.list(unname(x)), paste0(prefix, seq_along(x), ":", labels))
  }
  # sdreport returns a summary per kind: the fixed effects, the random effects
  # and the derived quantities. The random and derived summaries carry their own
  # estimates, so each is kept whole rather than lined up against the parameter
  # vector, which is numbered across all three.
  summary_rows <- function(kind, summary) {
    if (is.null(summary) || !NROW(summary)) return(NULL)
    labels <- if (is.null(rownames(summary))) rep("", NROW(summary)) else rownames(summary)
    tags <- paste0(seq_len(NROW(summary)), ":", labels)
    c(stats::setNames(as.list(unname(summary[, "Estimate"])),
                      paste0(kind, "_estimate:", tags)),
      stats::setNames(as.list(unname(summary[, "Std. Error"])),
                      paste0(kind, "_error:", tags)))
  }
  # Both summaries grow with the model: one random effect per year, one derived
  # value per year or per year and age. Two builds that agree at 30 years will
  # agree at 120, so only the normal size records them and the large runs stay
  # about memory.
  model_size <- if (is.null(values$model_size)) "normal" else values$model_size
  whole_fit <- identical(model_size, "normal")
  recorded <- c(recorded,
                named("parameter:", values$initial_parameters),
                numbered("estimate:", values$final_parameters),
                numbered("standard_error:", standard_errors),
                if (whole_fit) summary_rows("random", values$random),
                if (whole_fit) summary_rows("derived", values$report))

  # Whole numbers (bytes, counts) written out in full, not as 3.59e+08, so
  # results.tsv reads cleanly in any tool; parameters keep full precision.
  as_text <- function(x) {
    x <- x[[1L]]
    if (is.numeric(x) && is.finite(x) && x == round(x) && abs(x) < 1e15) {
      formatC(x, format = "f", digits = 0L)
    } else {
      format(x, digits = 15L)
    }
  }
  metric <- names(recorded)
  data.frame(
    ref = ref, source = "reference", fims_version = version,
    # Which entry points the build used, where the merge only knows what was
    # asked for.
    backend = if (is.null(values$backend)) "" else values$backend,
    metric = metric,
    unit = ifelse(metric %in% c("maximum_rss", "stage_rss_added", "peak_footprint"), "bytes",
           ifelse(grepl(paste0("objective|gradient|sd_|^parameter:|^estimate:|",
                               "^standard_error:|^random_|^derived_"),
                        metric), "value", "count")),
    value = unname(vapply(recorded, as_text, character(1))),
    path = basename(path),
    stringsAsFactors = FALSE)
}

#' Compare two FIMS refs on one stage of the interface ladder
#'
#' Installs each ref into its own library, then profiles one model run per ref.
#' The inputs are built inside the profiled process, but recording starts after
#' it, so what is recorded is the stage.
#'
#' @param ref_first Baseline branch, tag, or commit: every other ref is
#'   compared against it.
#' @param ref_compare One or more refs to compare with `ref_first`.
#' @param profiles Any of "memory" (Valgrind or Instruments allocations), "cpu"
#'   (perf or the Instruments time profiler) and "leaks" (memcheck or the macOS
#'   leaks tool). Each is a separate model run. "bench" adds back-to-back runs:
#'   the stage built and cleared repeatedly in one process, for memory growth
#'   and bench::mark() timing.
#' @param stage The stopping point of the model run, so "sdreport" runs
#' everything below it. Every stage also gets an unprofiled reference run on
#' the optimized build.
#' @param backend "TMB" or "quadra", and every ref must provide what is asked
#'   for or the run fails. Only meaningful from "helper": Quadra builds its
#'   own model and skips TMB's tape entirely.
#' @param teardown "none" leaves the interface objects alive, so the heap at
#'   exit is what the run retained; "clear" and "release" test whether that
#'   memory is returned.
#' @param size Inputs size, passed to setup_fims_inputs(): "normal" is
#'   data_big as shipped (30 years), "large" expands it to 120.
#' @param mem_baseline Also profile an inputs-only run, so the report can
#'   subtract everything that is not the stage.
#' @param n_eval fn/gr evaluations at stage "evaluate".
#' @param bench_iterations Cycles in each back-to-back loop, for "bench".
#' @param label Appended to the run directory name. A full analysis runs the
#'   same refs many times, so without a label each run would overwrite the last.
#' @param overwrite Replace an earlier run of the same comparison from the same
#'   day. FALSE keeps it and adds a numbered suffix.
#' @param reinstall Rebuild FIMS even when the cached build is already at the
#'   commit the ref points at. Builds are cached in `outputs/.lib-cache` and
#'   reused, since compiling FIMS from source is the slowest part of a run.
#' @param macos_instruments Capture Instruments traces on macOS.
#' @param instruments_attach_delay Seconds the workload waits, after loading the
#'   inputs, for a profiler to attach. Raise it on a slow host.
#' @param instruments_time_limit Maximum Instruments recording duration.
#' @return Invisibly, the path to this run's output directory.
run_fims_benchmark <- function(ref_first = "main",
                               ref_compare = "xptr-refactor",
                               profiles = c("memory", "cpu", "leaks"),
                               stage = c("initialize", "tape", "evaluate",
                                         "optimize", "sdreport", "helper"),
                               backend = c("TMB", "quadra"),
                               teardown = c("none", "clear", "release"),
                               size = c("normal", "large"),
                               mem_baseline = TRUE,
                               n_eval = 1L,
                               bench_iterations = 20L,
                               label = "",
                               overwrite = TRUE,
                               reinstall = FALSE,
                               macos_instruments = TRUE,
                               instruments_attach_delay = 6,
                               instruments_time_limit = "30m") {

  if ("FIMS" %in% loadedNamespaces()) {
    stop("Start a fresh R session: FIMS is already loaded, and installing a ",
         "different build over a mapped DLL is unreliable.", call. = FALSE)
  }

  profiles <- match.arg(profiles, c("memory", "cpu", "leaks", "bench"), several.ok = TRUE)
  stage <- match.arg(stage)
  backend <- match.arg(backend)
  teardown <- match.arg(teardown)
  size <- match.arg(size)

  refs <- resolve_refs(ref_first, ref_compare)

  repo_root <- normalizePath(
    if (requireNamespace("here", quietly = TRUE)) here::here() else getwd(),
    mustWork = TRUE
  )
  host <- Sys.info()[["sysname"]]

  # ---- run directory ------------------------------------------------------
  # Local date, not UTC
  run_date <- format(Sys.time(), "%Y%m%d")
  label_suffix <- if (nzchar(label)) paste0("_", path_safe(label)) else ""
  compare_names <- paste(vapply(refs[-1], path_safe, character(1)), collapse = "_vs_")
  if (!nzchar(compare_names)) compare_names <- "alone"
  output_dir <- file.path(repo_root, "outputs",
                          paste0(run_date, "_", path_safe(ref_first),
                                 "_vs_", compare_names, label_suffix))
  if (dir.exists(output_dir) && isTRUE(overwrite)) {
    message("Replacing the earlier run in ", basename(output_dir))
    unlink(output_dir, recursive = TRUE)
  }
  suffix <- 1L
  while (dir.exists(output_dir)) {
    suffix <- suffix + 1L
    output_dir <- paste0(sub("_[0-9]+$", "", output_dir), "_", suffix)
  }
  dir.create(output_dir, recursive = TRUE, showWarnings = FALSE)
  run_id <- basename(output_dir)
  log_file <- file.path(output_dir, "run.log")

  message(sprintf("Run %s: '%s' vs %s | stage=%s | size=%s | teardown=%s | profiles=%s",
                  run_id, ref_first,
                  paste0("'", paste(refs[-1], collapse = "', '"), "'"),
                  stage, size, teardown,
                  paste(profiles, collapse = ",")))

  # ---- install each ref into its own library ------------------------------
  # The optimized build is always needed: the reference run uses it, whatever
  # the profilers are.
  build_types <- unique(c(
    if (any(c("memory", "leaks") %in% profiles)) "debug",
    "profile"
  ))
  builds <- list()

  for (build_type in build_types) {
    # Checked in under scripts/, not generated: the flags do not depend on what
    # is being compared. A copy goes into the run directory so a set of results
    # still records the flags that produced it.
    makevars <- file.path(repo_root, "scripts", paste0("Makevars.", build_type))
    if (!file.exists(makevars)) {
      stop("Missing ", makevars, call. = FALSE)
    }
    file.copy(makevars, file.path(output_dir, basename(makevars)), overwrite = TRUE)

    for (ref in refs) {
      # Libraries live outside the run directory and are reused: a source build
      # of FIMS is the slowest part of a run, and rebuilding an unchanged commit
      # gains nothing.
      lib <- file.path(repo_root, "outputs", ".lib-cache", build_type, path_safe(ref))
      dir.create(lib, recursive = TRUE, showWarnings = FALSE)
      sha_file <- file.path(lib, ".installed-sha")
      wanted_sha <- resolve_ref_sha(ref)
      cached_sha <- if (file.exists(sha_file)) readLines(sha_file, warn = FALSE)[[1]] else NA_character_
      # An interrupted install leaves the directory behind with no DESCRIPTION
      # and no compiled library, and reusing that fails much later with "there
      # is no package called 'FIMS'". Both are checked, so a husk reinstalls.
      have_build <- file.exists(file.path(lib, "FIMS", "DESCRIPTION")) &&
        length(list.files(file.path(lib, "FIMS", "libs"), recursive = TRUE)) > 0L
      # R_LIBS prepends; R_LIBS_USER would *replace* the user library and hide
      # every package already installed there, so remotes would rebuild the
      # whole dependency tree for each ref.
      env <- c(paste0("R_LIBS=", shQuote(lib)),
               paste0("R_MAKEVARS_USER=", shQuote(makevars)),
               "R_REMOTES_UPGRADE=never",
               paste0("REPO_ROOT=", shQuote(repo_root)),
               paste0("FIMS_REF=", shQuote(ref)))

      reuse <- have_build && !isTRUE(reinstall) &&
        !is.na(cached_sha) && !is.na(wanted_sha) && identical(cached_sha, wanted_sha)

      build_profile <- file.path(
        output_dir, paste0("build_profile_", build_type, "_", path_safe(ref), ".txt"))

      if (reuse) {
        message("  reusing ", ref, " (", build_type, ") at ", substr(cached_sha, 1, 7))
      } else {
      message("  installing ", ref, " (", build_type, ")")
      # Wrapped in /usr/bin/time so the build itself is a measurement: a
      # refactor that halves run time but doubles compile time is worth seeing.
      install_command <- c("-e", shQuote(paste0(
        "source(file.path(Sys.getenv('REPO_ROOT'), 'R', 'setup_FIMS.R')); ",
        "install_fims(Sys.getenv('FIMS_REF'))")))
      # GNU time is a separate package on Debian (`apt install time`); the
      # shell keyword cannot write a file, so without it the build simply is
      # not measured and the console summary shows build cost as missing.
      if (file.exists("/usr/bin/time")) {
        time_flag <- if (identical(host, "Darwin")) "-l" else "-v"
        code <- run_logged("/usr/bin/time",
                           c(time_flag, "-o", shQuote(build_profile), "Rscript", install_command),
                           env = env, log = log_file)$status
      } else {
        code <- run_logged("Rscript", install_command, env = env, log = log_file)$status
      }
      if (code != 0L) {
        stop("Installing '", ref, "' (", build_type, ") failed; see ", log_file, call. = FALSE)
      }
      if (!is.na(wanted_sha)) writeLines(wanted_sha, sha_file) else unlink(sha_file)
      }

      # Report where FIMS was found as well as its version: with the user
      # library still visible, a failed install would otherwise fall back to a
      # previously installed FIMS without saying so.
      found <- tail(system2("Rscript",
                            c("-e", shQuote(paste0("cat(as.character(packageVersion('FIMS')), ",
                                                   "dirname(system.file(package = 'FIMS')), sep = '|')"))),
                            env = env, stdout = TRUE), 1L)
      if (!length(found) || !nzchar(found)) {
        stop("Could not read the FIMS version from ", lib,
             ". The install reported success but left nothing installed; see ",
             log_file, call. = FALSE)
      }
      parts <- strsplit(found, "|", fixed = TRUE)[[1]]
      version <- parts[[1]]
      if (length(parts) < 2 || !identical(normalizePath(parts[[2]], mustWork = FALSE),
                                          normalizePath(lib, mustWork = FALSE))) {
        stop("FIMS for '", ref, "' (", build_type, ") was loaded from ",
             if (length(parts) > 1) parts[[2]] else "an unknown library",
             " rather than ", lib, "; the install did not land where it should.",
             call. = FALSE)
      }

      builds[[build_type]][[ref]] <- list(
        lib = lib, version = version, sha = wanted_sha,
        # A reused build was not compiled in this run, so there is no profile.
        build_profile = if (file.exists(build_profile)) build_profile else "")
    }
  }

  versions <- vapply(refs, function(ref) builds[[build_types[[1]]]][[ref]]$version,
                     character(1))

  # Two branches often share a DESCRIPTION version, so record the commit each
  # ref resolved to. This is the file to check when a result looks wrong.
  utils::write.table(
    data.frame(
      ref = refs,
      version = versions,
      commit = vapply(refs, function(ref) {
        sha <- builds[[build_types[[1]]]][[ref]]$sha
        if (is.null(sha) || is.na(sha)) "unknown" else sha
      }, character(1)),
      library = vapply(refs, function(ref) builds[[build_types[[1]]]][[ref]]$lib,
                       character(1)),
      stringsAsFactors = FALSE),
    file.path(output_dir, "refs.tsv"), sep = "\t", row.names = FALSE, quote = FALSE)

  # ---- profile ------------------------------------------------------------
  # inputs.tsv records every artifact produced; scripts/tidy.py turns the
  # reporters' own parses into results.tsv (Phase 5).
  inputs <- list()

  # The summarizers take file paths in fixed argument shapes, so the driver
  # accumulates those vectors as the measurements happen.
  summary_args <- character()      # memory: --run REF VERSION <prefix|profile> [status trace]
  baseline_args <- character()     # memory: --baseline REF PREFIX
  cpu_summary_args <- character()  # cpu:    --run REF VERSION STATUS PATH
  native_profiles <- list()        # macOS /usr/bin/time -l profiles, per ref
  trace_status <- list()           # macOS Instruments status, per ref
  trace_paths <- list()            # macOS Instruments trace bundle, per ref
  reports <- character()           # files this run produced that someone reads

  add_input <- function(kind, ref, stage_label, round, tag, path) {
    inputs[[length(inputs) + 1L]] <<- data.frame(
      kind = kind, ref = ref, version = versions[[ref]], stage = stage_label,
      round = round, tag = tag, path = path, stringsAsFactors = FALSE)
  }

  profile_run <- function(script, args, env = character(), capture = FALSE) {
    args <- c(shQuote(file.path(repo_root, "scripts", script)), args)
    result <- run_logged("bash", args, env = env, log = log_file)
    if (capture) {
      # The wrapper prints one status word, but its diagnostics land in the same
      # captured stream, so match the word rather than trusting the last line.
      states <- grep("^(captured|captured-export-failed|failed|unavailable|disabled)$",
                     result$output, value = TRUE)
      if (length(states)) tail(states, 1L) else "failed"
    } else {
      result$status
    }
  }

  status <- integer()

  # One place that says what the model run is. Every measurement inherits these,
  # profiled or not, so a setting is written here and read by Sys.getenv() in the
  # script that uses it, with nothing in between translating it.
  model_env <- function(build_type, ref, ...) {
    c(paste0("R_LIBS=", shQuote(builds[[build_type]][[ref]]$lib)),
      paste0("REPO_ROOT=", shQuote(repo_root)),
      paste0("FIMS_STAGE=", stage),
      paste0("FIMS_SIZE=", size),
      paste0("FIMS_BACKEND=", backend),
      paste0("TEARDOWN=", teardown),
      paste0("FIMS_N_EVAL=", as.integer(n_eval)),
      ...)
  }

  # The R side of every unprofiled model process: a fresh Rscript that sources
  # the model functions and calls one. It finds the file through REPO_ROOT,
  # which model_env() sets, so the path needs no quoting of its own.
  r_call <- function(fn) {
    c("-e", shQuote(paste0("source(file.path(Sys.getenv('REPO_ROOT'), 'R', ",
                           "'run_model_for_profilers.R')); ", fn, "()")))
  }

    # The reference run: the stage once more per ref, on the optimized build, with
  # no profiler attached. It is the source of every "what a user would see"
  # number -- peak resident memory -- and of validation: the parameter values
  # the model holds at the end of the rung, and from optimize up the fit.
  # Profilers are for attribution; they distort both of these. Timing is not
  # taken from it: that belongs to bench::mark(), which repeats.
  #
  # Peak RSS comes from the kernel's VmHWM on Linux, read inside the run. macOS
  # has no /proc, so there the run goes under /usr/bin/time -l.
  values_args <- character()
  for (ref in refs) {
    build <- builds[["profile"]][[ref]]
    out <- file.path(output_dir, paste0("reference_", path_safe(ref), ".rds"))
    time_out <- sub("[.]rds$", "_time.txt", out)
    message("  reference run (unprofiled, optimized build): ", ref)
    command <- if (identical(host, "Darwin")) "/usr/bin/time" else "Rscript"
    args <- c(if (identical(host, "Darwin")) c("-l", "-o", shQuote(time_out), "Rscript"),
              r_call("run_model_for_cpp_profiler"))
    code <- run_logged(
      command, args,
      env = model_env("profile", ref, paste0("VALUES_OUT=", shQuote(out))),
      log = log_file)$status
    # Fail fast: without this run there is no peak RSS and no validation.
    if (code != 0L || !file.exists(out)) {
      stop("Reference run for '", ref, "' exited with status ", code, ". See ",
           log_file, call. = FALSE)
    }
    values_args <- c(values_args, shQuote(ref), shQuote(out))
  }
  status[["reference"]] <- 0L

  if ("memory" %in% profiles) {
    tool <- if (identical(host, "Darwin")) "time" else "massif"
    kind <- if (identical(host, "Darwin")) "time" else "massif"
    memory_status <- 0L

    for (ref in refs) {
      build <- builds[["debug"]][[ref]]

      if (isTRUE(mem_baseline)) {
        out <- file.path(output_dir, paste0("baseline_", path_safe(ref), ".out"))
        message("  memory baseline: ", ref)
        code <- profile_run("memory.sh",
                            c("--tool", tool, "--out", shQuote(out)),
                            env = model_env("debug", ref, "STAGE_MODE=inputs"))
        # Fail on the first failure rather than repeating it for every ref and
        # profiler: when the model itself is broken, every later measurement
        # fails the same way and each one is slow.
        if (code != 0L) {
          stop("Memory baseline for '", ref, "' exited with status ", code,
               ". See ", log_file, call. = FALSE)
        }
        add_input(kind, ref, "inputs", 1L, "", out)
        if (identical(tool, "massif")) {
          baseline_args <- c(baseline_args, "--baseline", shQuote(ref), shQuote(out))
        }
      }

      if (identical(host, "Darwin") && isTRUE(macos_instruments)) {
        trace <- file.path(output_dir, paste0("alloc_", path_safe(ref), ".trace"))
        message("  Instruments allocations: ", ref)
        profile_run("memory.sh",
                    c("--tool", "instruments", "--out", shQuote(trace),
                      "--attach-delay", instruments_attach_delay,
                      "--time-limit", instruments_time_limit),
                    env = model_env("debug", ref, "STAGE_MODE=stage"))
        add_input("instruments-alloc", ref, stage, 1L, "", trace)
        trace_status[[ref]] <- if (file.exists(trace)) "captured" else "failed"
        trace_paths[[ref]] <- trace
      }
    }

    # One profiled model run per ref. Repetition belongs in the R profiler,
    # where bench::mark() can iterate without a profiler distorting the result.
    for (ref in refs) {
      build <- builds[["debug"]][[ref]]
      out <- file.path(output_dir, paste0("massif_", path_safe(ref), ".out"))
      message("  memory profile: ", ref)
      code <- profile_run("memory.sh",
                          c("--tool", tool, "--out", shQuote(out)),
                          env = model_env("debug", ref, "STAGE_MODE=stage"))
      if (code != 0L) {
        stop("Memory profile for '", ref, "' exited with status ", code,
             ". See ", log_file, call. = FALSE)
      }
      add_input(kind, ref, stage, 1L, "", out)
      if (identical(tool, "massif")) {
        summary_args <- c(summary_args, "--run", shQuote(ref), shQuote(build$version),
                          shQuote(out))
      } else {
        # macOS: the memory run is /usr/bin/time, so this is where its maximum
        # RSS and peak footprint are, whether or not Instruments also ran.
        native_profiles[[ref]] <- out
        trace <- if (is.null(trace_status[[ref]])) "not run" else trace_status[[ref]]
        trace_path <- if (is.null(trace_paths[[ref]])) "none" else trace_paths[[ref]]
        summary_args <- c(summary_args, "--run", shQuote(ref), shQuote(build$version),
                          shQuote(out), shQuote(trace), shQuote(trace_path))
      }
    }

    status[["memory"]] <- memory_status
  }

  if ("cpu" %in% profiles) {
    tool <- if (identical(host, "Darwin")) "instruments" else "perf"
    cpu_states <- character()
    for (ref in refs) {
      build <- builds[["profile"]][[ref]]
      out <- file.path(output_dir, paste0("cpu_", path_safe(ref),
                                          if (tool == "perf") ".data" else ".trace"))
      report <- file.path(output_dir, paste0("cpu_", path_safe(ref), ".txt"))
      message("  CPU profile: ", ref)
      state <- profile_run("performance.sh",
                           c("--tool", tool, "--out", shQuote(out),
                             "--report", shQuote(report),
                             "--event", shQuote(Sys.getenv("PERF_EVENT", "")),
                             "--attach-delay", instruments_attach_delay,
                             "--time-limit", instruments_time_limit),
                           env = model_env("profile", ref, "STAGE_MODE=stage"),
                           capture = TRUE)
      cpu_states[[ref]] <- state
      # Fail fast. The preflight check in main.R should have caught a perf that
      # cannot record; if it still records nothing here, every later run would
      # fail the same way, and finding out after the whole analysis wastes it.
      if (state %in% c("failed", "unavailable")) {
        stop("CPU profile for '", ref, "' recorded nothing (", state, "). See ",
             log_file, " and \"Fixing Valgrind and perf installation\" in README.md.",
             call. = FALSE)
      }
      add_input("cpu-status", ref, stage, 1L, state, report)
      cpu_summary_args <- c(cpu_summary_args, "--run", shQuote(ref), shQuote(build$version),
                            shQuote(state), shQuote(report))
      if (grepl("^captured", state)) {
        add_input(if (tool == "perf") "perf" else "instruments-cpu",
                  ref, stage, 1L, "", report)
      }
    }
    status[["cpu"]] <- if (any(cpu_states == "failed")) 1L else 0L
  }

  # Leaks: the stage once more per ref under a leak detector -- Valgrind
  # memcheck on Linux, leaks on macOS -- on the debug build so allocation stacks
  # resolve. Fail fast, like the other profilers: a detector that cannot run
  # here fails every run the same way.
  leak_args <- character()
  if ("leaks" %in% profiles) {
    for (ref in refs) {
      build <- builds[["debug"]][[ref]]
      out <- file.path(output_dir,
                       paste0("leaks_", path_safe(ref), "_", build$version, ".json"))
      message("  leak check: ", ref)
      code <- run_logged(
        "python3",
        c(shQuote(file.path(repo_root, "scripts", "check_leaks.py")),
          "--ref", shQuote(ref), "--output", shQuote(out)),
        env = model_env("debug", ref),
        log = log_file)$status
      # The checker exits 0 even when the detector could not run, and records
      # that in the JSON instead, so the status is read from there.
      state <- if (file.exists(out)) {
        sub('.*"status": "([^"]*)".*', "\\1", paste(readLines(out, warn = FALSE), collapse = " "))
      } else "failed"
      if (code != 0L || state %in% c("failed", "unavailable")) {
        stop("Leak check for '", ref, "' did not complete (",
             if (code != 0L) paste("exit status", code) else state, "). See ", log_file,
             " and ", sub("[.]json$", ".log", out), ".", call. = FALSE)
      }
      leak_args <- c(leak_args, out)
    }
    status[["leaks"]] <- 0L
  }

  # Back-to-back runs: the stage built, run and cleared repeatedly in one R
  # process on the optimized build, with no profiler. Memory still in use after
  # each cycle answers whether anything accumulates; bench::mark() over the same
  # cycle gives the timing. One process per ref, since two FIMS builds cannot
  # share one. Fail fast, like every other measurement.
  bench_files <- character()
  if ("bench" %in% profiles) {
    for (ref in refs) {
      build <- builds[["profile"]][[ref]]
      out <- file.path(output_dir, paste0("tidy_bench_", path_safe(ref), ".tsv"))
      message("  back-to-back runs (", bench_iterations, " cycles each): ", ref)
      code <- run_logged(
        "Rscript", r_call("run_model_for_R_profiler"),
        env = model_env("profile", ref,
                          paste0("BENCH_ITERATIONS=", as.integer(bench_iterations)),
                          paste0("BENCH_REF=", shQuote(ref)),
                          paste0("BENCH_VERSION=", shQuote(build$version)),
                          paste0("BENCH_OUT=", shQuote(out))),
        log = log_file)$status
      if (code != 0L || !file.exists(out)) {
        stop("Back-to-back runs for '", ref, "' exited with status ", code, ". See ",
             log_file, call. = FALSE)
      }
      bench_files <- c(bench_files, out)
    }
    status[["bench"]] <- 0L
  }

  # ---- report ---------------------------------------------------------------
  # Each summarizer parses the artifacts it knows and writes tidy rows; nothing
  # renders Markdown here. One document covers a whole analysis, and R/report.R
  # builds it from the results.tsv files, so a single run writes no report of
  # its own beyond the console summary below.

  tidy_files <- character()
  tidy_path <- function(name) {
    path <- file.path(output_dir, paste0("tidy_", name, ".tsv"))
    tidy_files <<- c(tidy_files, path)
    shQuote(path)
  }

  run_reporter <- function(command, args, produces) {
    result <- run_logged(command, args, log = log_file)
    if (result$status != 0L || !file.exists(produces)) {
      warning("Measurements from ", basename(produces), " were not collected; see ",
              log_file, call. = FALSE, immediate. = TRUE)
    }
    invisible(NULL)
  }

  if (length(cpu_summary_args)) {
    path <- tidy_path("cpu")
    run_reporter("python3",
                 c(shQuote(file.path(repo_root, "scripts", "summarize_cpu.py")),
                   "--platform", host, cpu_summary_args, "--tidy-out", path),
                 gsub("'", "", path, fixed = TRUE))
  }

  if (length(summary_args)) {
    summarizer <- if (identical(host, "Darwin")) "summarize_macos.py" else "summarize_massif.py"
    path <- tidy_path("memory")
    run_reporter("python3",
                 c(shQuote(file.path(repo_root, "scripts", summarizer)),
                   summary_args, baseline_args, "--tidy-out", path),
                 gsub("'", "", path, fixed = TRUE))
  }

  if (length(leak_args)) {
    leak_report <- file.path(output_dir, "leak_report.md")
    path <- tidy_path("leaks")
    run_reporter("python3",
                 c(shQuote(file.path(repo_root, "scripts", "check_leaks.py")),
                   "--report", shQuote(leak_args), "--output", shQuote(leak_report),
                   "--tidy-out", path),
                 gsub("'", "", path, fixed = TRUE))
  }

  # Validation and build cost are already in R, as an RDS and as a file
  # /usr/bin/time wrote, so they become rows here rather than through a
  # summarizer that would only have to read them back.
  tidy_rows <- function(rows, name) {
    if (!nrow(rows)) return(invisible(NULL))
    path <- file.path(output_dir, paste0("tidy_", name, ".tsv"))
    tidy_files <<- c(tidy_files, path)
    empty <- c("fims_version", "stage", "backend", "teardown", "size", "round", "iteration")
    rows[empty[!empty %in% names(rows)]] <- ""
    columns <- c("ref", "fims_version", "stage", "backend", "teardown", "size",
                 "round", "iteration", "source", "metric", "unit", "value", "path")
    utils::write.table(rows[, columns], path, sep = "\t", row.names = FALSE, quote = FALSE)
  }

  if (length(values_args)) {
    pairs <- matrix(gsub("'", "", values_args, fixed = TRUE), ncol = 2L, byrow = TRUE)
    rows <- do.call(rbind, lapply(seq_len(nrow(pairs)), function(index) {
      ref <- pairs[index, 1L]
      version <- builds[["profile"]][[ref]]$version
      reference_rows(ref, pairs[index, 2L], if (is.null(version)) "" else version)
    }))
    tidy_rows(rows, "reference")
  }

  build_rows <- do.call(rbind, lapply(refs, function(ref) {
    do.call(rbind, lapply(build_types, function(build_type) {
      profile <- builds[[build_type]][[ref]]$build_profile
      if (is.null(profile) || !nzchar(profile) || !file.exists(profile)) return(NULL)
      text <- readLines(profile, warn = FALSE)
      # GNU time reports kilobytes; /usr/bin/time -l on macOS reports bytes.
      hit <- grep("Maximum resident set size", text, value = TRUE)
      if (!length(hit)) return(NULL)
      kb <- suppressWarnings(as.numeric(sub(".*?([0-9]+).*", "\\1", hit[[1]])))
      if (!is.finite(kb)) return(NULL)
      data.frame(ref = ref, source = "build", metric = "peak_rss", unit = "bytes",
                 value = as.character(kb * if (identical(host, "Darwin")) 1 else 1024),
                 path = basename(profile), round = build_type, stringsAsFactors = FALSE)
    }))
  }))
  if (!is.null(build_rows)) tidy_rows(build_rows, "build")

  tidy_files <- c(tidy_files, bench_files)
  results_file <- file.path(output_dir, "results.tsv")
  existing <- tidy_files[file.exists(tidy_files)]
  if (length(existing)) {
    run_logged("python3",
               c(shQuote(file.path(repo_root, "scripts", "tidy.py")),
                 "--merge", shQuote(existing),
                 "--stage", stage, "--backend", backend,
                 "--teardown", teardown, "--size", size,
                 "--output", shQuote(results_file)),
               log = log_file)
    reports <- c(reports, results_file)
  }

  # Printed, not logged: this is the one piece of output meant for whoever is
  # watching the run.
  if (file.exists(results_file)) {
    system2("Rscript", c(shQuote(file.path(repo_root, "R", "report.R")),
                         "--console", shQuote(output_dir)))
  }

  # ---- name the run for what it compared ----------------------------------
  compare_label <- paste(vapply(refs[-1], function(ref) {
    label_text <- path_safe(ref)
    if (!identical(versions[[ref]], versions[[ref_first]])) {
      label_text <- paste0(label_text, "-", path_safe(versions[[ref]]))
    }
    label_text
  }, character(1)), collapse = "_vs_")
  if (!nzchar(compare_label)) compare_label <- "alone"
  renamed <- file.path(repo_root, "outputs",
                       paste0(run_date, "_", path_safe(ref_first), "-",
                              path_safe(versions[[ref_first]]), "_vs_", compare_label,
                              label_suffix))
  # The final name carries the version, so an earlier run of the same
  # comparison is replaced here too, not just at the pre-rename path.
  if (dir.exists(renamed) && isTRUE(overwrite) && !identical(renamed, output_dir)) {
    unlink(renamed, recursive = TRUE)
  }
  if (!dir.exists(renamed) && file.rename(output_dir, renamed)) {
    output_dir <- renamed
    run_id <- basename(renamed)
    log_file <- file.path(output_dir, basename(log_file))
  }

  manifest <- data.frame(
    run_id = run_id, label = label, stage = stage, teardown = teardown, size = size,
    backend = backend,
    ref_first = ref_first, ref_compare = paste(refs[-1], collapse = ","),
    profile = names(status), status = unname(status),
    timestamp = format(Sys.time(), "%Y-%m-%dT%H:%M:%S%z"),
    stringsAsFactors = FALSE)
  utils::write.table(manifest, file.path(output_dir, "manifest.tsv"),
                     sep = "\t", row.names = FALSE, quote = FALSE)

  message("Done: ", output_dir)
  for (path in reports) message("  report: ", basename(path))
  print(manifest[, c("profile", "status")])

  # Memory is the measurement the comparison rests on, so a failure there fails
  # the run. CPU profiles and leak checks are best effort:
  # they are recorded as incomplete and reported, but they do not discard
  # everything else this run produced.
  failed <- names(status)[status != 0L]
  fatal <- intersect(failed, "memory")
  if (length(setdiff(failed, fatal))) {
    warning("Incomplete but not fatal: ", paste(setdiff(failed, fatal), collapse = ", "),
            ". See ", log_file, call. = FALSE)
  }
  if (length(fatal)) {
    stop("These profiles did not complete: ", paste(fatal, collapse = ", "),
         ". See ", log_file, call. = FALSE)
  }

  invisible(output_dir)
}

