#!/usr/bin/env python3
"""Measure scoped R/C++ source metrics for the exact installed FIMS revision."""
import argparse
from collections import Counter
import contextlib
import hashlib
import io
import json
import math
from pathlib import Path, PurePosixPath
import re
import statistics
import subprocess
import shutil
import tarfile
import tempfile
import urllib.request

VERSION = '1.24.0'
CPP = {'.c', '.cc', '.cpp', '.cxx', '.h', '.hpp', '.hxx', '.ipp', '.tpp'}
VENDOR = {'quadra', 'eigen', 'eigen3', 'unsupported', 'lbfgspp', 'vendor', 'vendored', 'third_party', 'third-party', 'external'}
GENERATED = {'rcppexports.cpp', 'rcppexports.r', 'cpp11.cpp', 'cpp11.r'}


def scope(name, text):
    path = PurePosixPath(name)
    parts = [part.lower() for part in path.parts]
    language = 'R' if path.suffix.lower() == '.r' else 'C++' if path.suffix.lower() in CPP else None
    if language is None:
        return None, 'non-source'
    if any(part in VENDOR for part in parts):
        return language, 'vendored'
    if path.name.lower() in GENERATED or re.search(r'(automatically generated|generated by (rcpp|cpp11|roxygen)|do not edit)', text[:2000], re.I):
        return language, 'generated'
    if not (parts[0] in ('r', 'src') or parts[:2] == ['inst', 'include']):
        return language, 'tests-examples-other'
    return language, 'owned'


def source_files(source):
    for path in sorted(source.rglob('*')):
        if path.is_file() and not path.is_symlink() and '.git' not in path.parts:
            if path.suffix.lower() in CPP | {'.r'}:
                yield path.relative_to(source).as_posix(), path.read_text(errors='replace')


def archive_files(archive):
    with tarfile.open(fileobj=archive, mode='r:gz') as tar:
        for member in tar:
            path = PurePosixPath(member.name)
            if member.isfile() and len(path.parts) > 1 and path.suffix.lower() in CPP | {'.r'}:
                # Read members directly: no archive paths are extracted to disk.
                yield PurePosixPath(*path.parts[1:]).as_posix(), tar.extractfile(member).read().decode('utf-8', errors='replace')


def distribution(values):
    if not values:
        return dict(median=None, p95=None, maximum=None)
    values = sorted(values)
    return dict(median=statistics.median(values), p95=values[math.ceil(.95 * len(values))-1], maximum=max(values))


# A versioned lexical approximation, not a compiler-derived Halstead measure.
INDEX_METHOD = 'lexical-file-mi-v1'
KEYWORDS = {
    'R': set('if else repeat while function for in next break return'.split()),
    'C++': set(('alignas alignof asm auto bool break case catch char char8_t char16_t '
                'char32_t class concept const consteval constexpr constinit const_cast '
                'continue co_await co_return co_yield decltype default delete do double '
                'dynamic_cast else enum explicit export extern float for friend goto if '
                'inline int long mutable namespace new noexcept operator private protected '
                'public register reinterpret_cast requires return short signed sizeof static '
                'static_assert static_cast struct switch template this thread_local throw try '
                'typedef typeid typename union unsigned using virtual void volatile wchar_t '
                'while and and_eq bitand bitor compl not not_eq or or_eq xor xor_eq').split())
}


def halstead(name, source, language):
    """Count lexical operators/operands; retain raw counts for auditing."""
    import lizard
    reader = lizard.get_reader_for(name)(lizard.FileInfoBuilder(name))
    # Fix common compound tokens missing from the pinned lexer. C++ angle
    # brackets remain lexical: templates and comparisons are not disambiguated.
    addition = r'|<<-|->>|\[\[|\]\]|%[^%\n]*%|`[^`]*`' if language == 'R' else r'|<<=|>>=|<=>|<<|>>|%=|\*=|/=|->\*|\.\*'
    operators, operands = Counter(), Counter()
    for token in reader.generate_tokens(source, addition=addition):
        if token.isspace() or reader.get_comment_from_token(token) is not None:
            continue
        # Preprocessor directives are not expanded; exclude their whole token.
        if language == 'C++' and token.startswith('#'):
            continue
        if token in KEYWORDS[language] or not (token[0].isalnum() or token[0] in '_\"\'`' or
                                               (language == 'R' and token.startswith('.') and token != '...')):
            operators[token] += 1
        else:
            operands[token] += 1
    n1, n2 = len(operators), len(operands)
    N1, N2 = sum(operators.values()), sum(operands.values())
    vocabulary, length = n1 + n2, N1 + N2
    return dict(distinct_operators=n1, distinct_operands=n2, operators=N1, operands=N2,
                vocabulary=vocabulary, length=length,
                volume=length * math.log2(vocabulary) if vocabulary > 1 else 0)


def maintainability_index(volume, complexity, nloc):
    if volume <= 0 or nloc <= 0:
        return None
    return max(0.0, min(100.0, (171 - 5.2 * math.log(volume) -
                               .23 * complexity - 16.2 * math.log(nloc)) * 100 / 171))


def index_summary(files):
    measured = [f for f in files if f['mi'] is not None]
    weight = sum(f['nloc'] for f in measured)
    scores = sorted(f['mi'] for f in measured)
    total_nloc = sum(f['nloc'] for f in files)
    return dict(method=INDEX_METHOD, measured_files=len(measured), total_files=len(files),
                measured_nloc=weight, total_nloc=total_nloc,
                scored_nloc_percent=100 * weight / total_nloc if total_nloc else None,
                nloc_weighted_mean=sum(f['mi'] * f['nloc'] for f in measured) / weight if weight else None,
                file_mean=statistics.mean(scores) if scores else None,
                median=statistics.median(scores) if scores else None,
                p10=scores[math.ceil(.1 * len(scores))-1] if scores else None,
                minimum=min(scores) if scores else None,
                nloc_below_20_percent=100 * sum(f['nloc'] for f in measured if f['mi'] < 20) / weight if weight else None)


def analyze(files):
    import lizard
    from lizard_ext.lizardduplicate import LizardExtension
    if lizard.version != VERSION:
        raise ValueError(f'Lizard {VERSION} required; found {lizard.version}')
    inventory, by_language, warnings = [], {'R': [], 'C++': []}, []
    for name, text in sorted(files):
        language, category = scope(name, text)
        if language:
            inventory.append(dict(path=name, language=language, scope=category,
                                  sha256=hashlib.sha256(text.encode()).hexdigest()))
            if category == 'owned':
                by_language[language].append((name, text))
    languages = {}
    for language, sources in by_language.items():
        duplicate = LizardExtension()
        analyzer = lizard.FileAnalyzer(lizard.get_extensions([]) + [duplicate])
        infos, functions, file_metrics = [], [], []
        for name, text in sources:
            stderr = io.StringIO()
            with contextlib.redirect_stderr(stderr):
                info = analyzer.analyze_source_code(name, text)
            if stderr.getvalue():
                warnings.append(dict(path=name, message=stderr.getvalue()))
            infos.append(info)
            h = halstead(name, text, language)
            ccn = sum(f.cyclomatic_complexity for f in info.function_list)
            file_metrics.append(dict(path=name, nloc=info.nloc, complexity=ccn,
                                     function_count=len(info.function_list), halstead=h,
                                     mi=maintainability_index(h['volume'], ccn, info.nloc)))
            for function in info.function_list:
                functions.append(dict(path=name, name=function.name, line=function.start_line,
                                      end_line=function.end_line, nloc=function.nloc,
                                      complexity=function.cyclomatic_complexity,
                                      parameters=function.parameter_count))
        list(duplicate.cross_file_process(infos))
        clones = [[dict(path=s.file_name, start=s.start_line, end=s.end_line) for s in group]
                  for group in duplicate.get_duplicates(min_duplicate_tokens=70)] if infos else []
        rate = duplicate.duplicate_rate() if infos else None
        # An auditable path-based inventory, not a semantic coupling measurement.
        adapters = [info for info in infos if '/interface/' in info.filename.lower()
                    or re.search(r'(^|/)(native_|rcpp|quadra|call_)', info.filename.lower())]
        languages[language] = dict(index=index_summary(file_metrics), file_metrics=file_metrics, files=len(infos), nloc=sum(i.nloc for i in infos),
                                  functions=functions, function_count=len(functions),
                                  complexity=distribution([f['complexity'] for f in functions]),
                                  function_nloc=distribution([f['nloc'] for f in functions]),
                                  functions_over_ccn15=sum(f['complexity'] > 15 for f in functions),
                                  functions_over_100_lines=sum(f['nloc'] > 100 for f in functions),
                                  duplicate_token_percent=rate * 100 if rate is not None else None,
                                  duplicate_groups=clones,
                                  adapter_nloc=sum(i.nloc for i in adapters), adapter_files=[i.filename for i in adapters])
    return dict(schema_version=2, index=index_summary([f for v in languages.values() for f in v['file_metrics']]),
                status='partial' if warnings else 'measured', tool=f'lizard {VERSION}',
                languages=languages, inventory=inventory, warnings=warnings,
                exclusions=dict(Counter(item['scope'] for item in inventory if item['scope'] != 'owned')),
                unmeasured=['branch coverage (requires instrumented tests)', 'cognitive complexity',
                            'semantic coupling', 'static-analysis findings'])


def collect(args):
    result = dict(ref=args.ref, commit=args.sha or None, status='unavailable', languages={})
    try:
        import lizard  # Fail before downloading when the optional dependency is absent.
        if args.source:
            result.update(analyze(source_files(args.source)))
            result['source'] = 'local working tree; inventory hashes identify analyzed contents'
        else:
            if not re.fullmatch(r'[0-9a-fA-F]{40}', args.sha or ''):
                raise ValueError('Installed package RemoteSha is missing; refusing to analyze a moving branch instead')
            url = f'https://codeload.github.com/NOAA-FIMS/FIMS/tar.gz/{args.sha}'
            with tempfile.TemporaryFile() as archive:
                curl = '/usr/bin/curl' if Path('/usr/bin/curl').is_file() else shutil.which('curl')
                if curl:
                    subprocess.run([curl, '--fail', '--location', '--silent', '--show-error',
                                    '--max-time', '120', url], stdout=archive,
                                   stderr=subprocess.PIPE, check=True)
                else:
                    with urllib.request.urlopen(url, timeout=120) as response:
                        while chunk := response.read(1024 * 1024):
                            archive.write(chunk)
                archive.seek(0)
                result.update(analyze(archive_files(archive)))
            result['source'] = url
    except ImportError as error:
        result.update(reason='Lizard unavailable: install scripts/requirements-maintainability.txt in .venv-maintainability or set MAINTAINABILITY_PYTHON', languages={})
    except Exception as error:
        result.update(status='unavailable', reason=str(error), languages={})
    args.output.write_text(json.dumps(result, indent=2) + '\n')
    print(f"Maintainability {args.ref}: {result['status']}")


def display(value):
    return 'Not measured' if value is None else f'{value:.2f}' if isinstance(value, float) else str(value)


def escape(value):
    return str(value).replace('|', '\\|').replace('\n', ' ').replace('`', "'")


def report(paths):
    data = [json.loads(path.read_text()) for path in paths]
    lines = ['# FIMS Maintainability Report', '',
             'R and C++ are measured separately. Only FIMS-owned production source is included; vendored, generated, test, and example code are inventoried separately. A lexical file-level Maintainability Index (MI) estimate supplements the source metrics; higher scores indicate less structural complexity under this method.', '',
             '## Summary', '',
             '| Ref | Language | Status | Files | NLOC | Functions | CCN median / p95 / max | Function NLOC median / p95 / max | CCN >15 | Duplicate tokens % | Adapter NLOC |',
             '|---|---|---|---:|---:|---:|---|---|---:|---:|---:|']
    for result in data:
        if not result.get('languages'):
            lines.append(f"| {escape(result['ref'])} | — | {escape(result['status'])} | — | — | — | — | — | — | — | — |")
        for language, values in result.get('languages', {}).items():
            dist = lambda key: ' / '.join(display(values[key][k]) for k in ('median','p95','maximum'))
            lines.append(f"| {escape(result['ref'])} | {language} | {result['status']} | {values['files']} | {values['nloc']} | {values['function_count']} | {dist('complexity')} | {dist('function_nloc')} | {values['functions_over_ccn15']} | {display(values['duplicate_token_percent'])} | {values['adapter_nloc']} |")
    lines += ['', '### Maintainability Index estimate (0–100; higher is better)', '',
              '| Ref | Scope | NLOC-weighted MI | Equal-file MI | Median / p10 / minimum | NLOC in files with MI <20 (%) | Scored files / total | Scored NLOC % |',
              '|---|---|---:|---:|---|---:|---|---:|']
    for result in data:
        scopes = [('Overall', result)] + list(result.get('languages', {}).items())
        for label, values in scopes:
            mi = values.get('index', {})
            dist = ' / '.join(display(mi.get(k)) for k in ('median', 'p10', 'minimum'))
            lines.append(f"| {escape(result['ref'])} | {label} | {display(mi.get('nloc_weighted_mean'))} | {display(mi.get('file_mean'))} | {dist} | {display(mi.get('nloc_below_20_percent'))} | {mi.get('measured_files', '—')} / {mi.get('total_files', '—')} | {display(mi.get('scored_nloc_percent'))} |")
    lines += index_interpretation(data)
    lines += ['', '## Method and limitations', '',
              f'- Analyzer: Lizard {VERSION}. CCN is its cyclomatic-complexity estimate; NLOC excludes comments and blank lines. These are parser-based source metrics, not compiler or semantic analysis.',
              '- Duplicate percentage uses Lizard’s duplicate-token rate, with a 70-token minimum, separately within each language. It is not duplicated-line coverage.',
              '- p95 uses nearest rank. CCN >15 and functions >100 NLOC are review flags, not pass/fail judgments.',
              '- Adapter NLOC is a path-based estimate: owned interface directories and filenames beginning native_, rcpp, quadra, or call_. JSON lists the matching files for review.',
              '- Production roots: R/, src/, inst/include/. Vendored directories (including Quadra/Eigen/LBFGSpp/external), known generated bindings, and files with generated-code markers are excluded. Review the JSON inventory when ownership conventions change.',
              f'- MI method: `{INDEX_METHOD}`. Per file: `max(0, (171 - 5.2 ln(V) - 0.23 G - 16.2 ln(L)) * 100 / 171)`, where V is lexical Halstead volume, G is the sum of Lizard function CCN, and L is file NLOC. Empty/zero-volume files are unscored, not assigned 100. No comment bonus.',
              '- Halstead volume: `(N1 + N2) * log2(n1 + n2)`, using total and distinct operator/operand counts. Keywords and punctuation (including delimiters) are operators; identifiers, function names and literals are operands. Comments and C++ preprocessor directives are excluded from volume. Macros are not expanded; template syntax and overloaded operators are not resolved. Lizard may miss top-level decisions or nested constructs. This is a lexical estimate, not a Visual Studio-compatible measurement.',
              '- Overall MI is the NLOC-weighted mean of scored file indexes across R and C++; per-language results and equal-file means show sensitivity to code mix and file organization. MI is computed before aggregation, never on concatenated branch totals. R and C++ scores are not calibrated for cross-language difficulty. A different file split or weighting can change the ranking.',
              '- Median, lower-decile p10 (nearest rank), minimum, and the share of scored NLOC in files below 20 expose low-scoring code. The <20 cutoff is a review aid, not a validated quality classification for this estimator. Raw inputs and scoring coverage are retained in JSON. Parser warnings make the result partial; historical JSON without MI requires reanalysis.',
              '- Duplication and adapter size remain separate evidence: they are not inputs to the standard MI formula. Branch coverage, cognitive complexity, semantic coupling, and static-analysis findings are **not measured**. Coverage needs instrumented tests; it cannot be inferred from passing test counts.',
              '- Formula: [Microsoft Maintainability Index](https://learn.microsoft.com/en-us/visualstudio/code-quality/code-metrics-maintainability-index-range-and-meaning). Halstead definitions and cautions: [Radon metrics](https://radon.readthedocs.io/en/master/intro.html).',
              '- Compare branches with the same analyzer and scope. A smaller codebase or higher MI alone does not prove easier maintenance.',
              '- Tool documentation: [Lizard](https://github.com/terryyin/lizard).', '']
    for result, path in zip(data, paths):
        lines += [f"## {escape(result['ref'])}", '', f"Commit: `{escape(result.get('commit') or 'unrecorded')}`. Details: [{path.name}]({path.name}).", '']
        if result.get('reason'):
            lines += [f"Not measured: {escape(result['reason'])}", '']
        if result.get('exclusions'):
            lines += ['Excluded source-file counts: ' + ', '.join(f'{k}: {v}' for k,v in result['exclusions'].items()), '']
        for language, values in result.get('languages', {}).items():
            lines += [f'### {language}: highest-complexity functions', '', '| Function | File:line | CCN | NLOC |', '|---|---|---:|---:|']
            for f in sorted(values['functions'], key=lambda f: (-f['complexity'], -f['nloc']))[:10]:
                lines.append(f"| {escape(f['name'])} | {escape(f['path'])}:{f['line']} | {f['complexity']} | {f['nloc']} |")
            lines += ['', f'### {language}: lowest file MI estimates', '',
                      '| File | MI | NLOC | Total function CCN | Halstead volume |', '|---|---:|---:|---:|---:|']
            for f in sorted((f for f in values.get('file_metrics', []) if f['mi'] is not None), key=lambda f: (f['mi'], -f['nloc']))[:10]:
                lines.append(f"| {escape(f['path'])} | {display(f['mi'])} | {f['nloc']} | {f['complexity']} | {display(f['halstead']['volume'])} |")
            lines.append('')
    lines += comparison_details(data)
    return '\n'.join(lines)


def index_interpretation(data):
    available = [r for r in data if r.get('index', {}).get('nloc_weighted_mean') is not None]
    if len(available) < 2:
        return []
    weighted = sorted(available, key=lambda r: -r['index']['nloc_weighted_mean'])
    equal = max(available, key=lambda r: r['index']['file_mean'])
    first, second = weighted[:2]
    gap = first['index']['nloc_weighted_mean'] - second['index']['nloc_weighted_mean']
    lines = ['', f"Among scored branches, `{escape(first['ref'])}` has the highest NLOC-weighted file MI, ahead of `{escape(second['ref'])}` by {gap:.2f} points. `{escape(equal['ref'])}` has the highest equal-file mean."]
    if first['ref'] != equal['ref']:
        lines += ['', 'The leading branch changes with weighting, so this index does **not** establish a robust overall maintainability winner.']
    lines += ['', 'This file-level estimator penalizes large files and can reach zero; its absolute values should not be interpreted as quality grades or compared with function-level/tool-specific MI scores. Coverage, coupling, and functional equivalence still require separate assessment.', '']
    return lines


def comparison_details(data):
    """Matched paths help distinguish changes from a different source inventory."""
    if len(data) < 2:
        return []
    baseline = data[0]
    lines = ['## File comparisons against baseline', '',
             f"Baseline: `{escape(baseline['ref'])}`. Same paths are compared; renames appear as added/removed. Deltas are branch minus baseline, so positive MI deltas are improvements under this method. These comparisons do not establish equivalent functionality.", '']
    for result in data[1:]:
        for language in ('R', 'C++'):
            a = baseline.get('languages', {}).get(language, {})
            b = result.get('languages', {}).get(language, {})
            if not a.get('file_metrics') or not b.get('file_metrics'):
                continue
            old = {f['path']: f for f in a['file_metrics']}
            new = {f['path']: f for f in b['file_metrics']}
            shared = old.keys() & new.keys()
            changes = [(new[p]['mi'] - old[p]['mi'], p) for p in shared
                       if new[p]['mi'] is not None and old[p]['mi'] is not None]
            # Fixed baseline weights prevent changing file size from changing weights.
            weight = sum(old[p]['nloc'] for _, p in changes)
            delta = sum(d * old[p]['nloc'] for d, p in changes) / weight if weight else None
            lines += [f"### {escape(result['ref'])}: {language}", '',
                      f"Shared paths: {len(shared)}; added: {len(new.keys() - old.keys())}; removed: {len(old.keys() - new.keys())}. Matched-file MI change (fixed baseline NLOC weights): {display(delta)}.", '',
                      '| Changed file (largest absolute MI changes) | Baseline MI | Branch MI | MI delta | NLOC delta |',
                      '|---|---:|---:|---:|---:|']
            for d, p in sorted(changes, key=lambda item: (-abs(item[0]), item[1]))[:10]:
                if abs(d) < .005:
                    continue
                lines.append(f"| {escape(p)} | {display(old[p]['mi'])} | {display(new[p]['mi'])} | {d:+.2f} | {new[p]['nloc'] - old[p]['nloc']:+d} |")
            lines.append('')
    return lines


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--quiet', action='store_true')
    parser.add_argument('--ref')
    parser.add_argument('--sha')
    parser.add_argument('--source', type=Path)
    parser.add_argument('--output', required=True, type=Path)
    parser.add_argument('--report', nargs='+', type=Path)
    args = parser.parse_args()
    if args.report:
        rendered = report(args.report)
        args.output.write_text(rendered)
        if not args.quiet:
            print('\nMaintainability comparison\n' + rendered.split('## Summary\n\n')[1].split('\n## Method')[0])
    elif args.ref:
        collect(args)
    else:
        parser.error('--ref or --report is required')
